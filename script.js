function showProducts(list=products){
let box=document.getElementById("products");
if(!box) return;

box.innerHTML="";

list.forEach(p=>{
box.innerHTML+=`
<div class="card">
<img src="${p.img}">
<h4>${p.name}</h4>
<p>${p.price} ج.م</p>

<button onclick="addToCart(${p.id})">اضافة للسلة</button>
<button onclick="openProduct(${p.id})">شراء</button>

</div>`;
});
}

